/**
 * Probe the LLM proxy: which base URL works, and which structured-output
 * method (jsonSchema / functionCalling / jsonMode) it supports.
 *
 *   pnpm probe            # print results only
 *   pnpm probe --write    # also update LLM_BASE_URL / LLM_STRUCTURED_MODE in .env
 *                         # and write docs/llm-probe.md
 *
 * The API key is read from .env and is never printed or written anywhere.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { ChatOpenAI } from '@langchain/openai';
import { z } from 'zod';

const ROOT = resolve(import.meta.dirname, '..');
const ENV_PATH = resolve(ROOT, '.env');
const DOC_PATH = resolve(ROOT, 'docs/llm-probe.md');
const CALL_TIMEOUT_MS = 60_000;

type Method = 'jsonSchema' | 'functionCalling' | 'jsonMode';
type StructuredMode = 'json_schema' | 'function_calling' | 'json_mode';

/** Preference order when several methods work. */
const METHODS: ReadonlyArray<{ method: Method; mode: StructuredMode }> = [
  { method: 'jsonSchema', mode: 'json_schema' },
  { method: 'functionCalling', mode: 'function_calling' },
  { method: 'jsonMode', mode: 'json_mode' },
];

interface Result {
  baseURL: string;
  method: Method;
  mode: StructuredMode;
  ok: boolean;
  ms: number;
  detail: string;
}

function candidateBaseURLs(raw: string): string[] {
  const base = raw.trim().replace(/\/+$/, '');
  const withV1 = base.endsWith('/v1') ? base : `${base}/v1`;
  return [...new Set([base, withV1])];
}

function redact(text: string, secret: string): string {
  const flat = text.replace(/\s+/g, ' ').trim();
  return secret ? flat.split(secret).join('***') : flat;
}

async function probeOne(
  baseURL: string,
  apiKey: string,
  model: string,
  { method, mode }: (typeof METHODS)[number],
): Promise<Result> {
  const started = Date.now();
  try {
    const llm = new ChatOpenAI({
      model,
      apiKey,
      configuration: { baseURL },
      timeout: CALL_TIMEOUT_MS,
      maxRetries: 0,
      temperature: 0,
    });
    const schema = z.object({ ok: z.boolean() });
    const structured = llm.withStructuredOutput(schema, { method, name: 'probe' });
    const out = await structured.invoke(
      'Respond with a JSON object of the form {"ok": true}. Set ok to true.',
      { signal: AbortSignal.timeout(CALL_TIMEOUT_MS) },
    );
    const parsed = schema.parse(out);
    return { baseURL, method, mode, ok: true, ms: Date.now() - started, detail: `ok=${parsed.ok}` };
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    return {
      baseURL,
      method,
      mode,
      ok: false,
      ms: Date.now() - started,
      detail: redact(message, apiKey).slice(0, 300),
    };
  }
}

/** When both URL forms work, prefer the canonical `/v1` form (listed last in candidates). */
function pickRecommendation(results: Result[], baseURLs: string[]) {
  for (const baseURL of [...baseURLs].reverse()) {
    const mode = METHODS.map((m) => m.mode).find((m) =>
      results.some((r) => r.baseURL === baseURL && r.mode === m && r.ok),
    );
    if (mode) return { baseURL, mode };
  }
  return undefined;
}

function renderDoc(results: Result[], rec: { baseURL: string; mode: StructuredMode }): string {
  const rows = results
    .map(
      (r) =>
        `| \`${r.baseURL}\` | \`${r.method}\` | ${r.ok ? 'OK' : 'FAIL'} | ${r.ms} | ${r.detail.replace(/\|/g, '\\|')} |`,
    )
    .join('\n');
  return `# LLM proxy probe

Generated by \`pnpm probe --write\` (\`scripts/probe-llm.ts\`). The API key is never written here.

Each cell calls \`ChatOpenAI.withStructuredOutput(z.object({ ok: z.boolean() }), { method })\` with a ${CALL_TIMEOUT_MS / 1000}s timeout.

| baseURL | method | result | ms | detail |
| --- | --- | --- | --- | --- |
${rows}

## Recommendation

- Working baseURL: \`${rec.baseURL}\`
- \`LLM_STRUCTURED_MODE=${rec.mode}\` (preference order: json_schema, function_calling, json_mode)
`;
}

function updateEnv(rec: { baseURL: string; mode: StructuredMode }): void {
  let text = readFileSync(ENV_PATH, 'utf8');
  const set = (key: string, value: string) => {
    const re = new RegExp(`^${key}=.*$`, 'm');
    text = re.test(text) ? text.replace(re, () => `${key}=${value}`) : `${text.trimEnd()}\n${key}=${value}\n`;
  };
  set('LLM_BASE_URL', rec.baseURL);
  set('LLM_STRUCTURED_MODE', rec.mode);
  writeFileSync(ENV_PATH, text);
}

async function main(): Promise<void> {
  process.loadEnvFile(ENV_PATH);
  const rawBase = process.env.LLM_BASE_URL ?? '';
  const apiKey = process.env.LLM_API_KEY ?? '';
  const model = process.env.LLM_MODEL || 'gpt-6.1-sol';
  if (!rawBase || !apiKey) {
    console.error('LLM_BASE_URL and LLM_API_KEY must be set in .env');
    process.exit(2);
  }

  const baseURLs = candidateBaseURLs(rawBase);
  const results: Result[] = [];
  console.log(`model=${model}`);
  for (const baseURL of baseURLs) {
    for (const m of METHODS) {
      const r = await probeOne(baseURL, apiKey, model, m);
      results.push(r);
      console.log(`${r.ok ? 'OK  ' : 'FAIL'} ${baseURL} ${r.method} (${r.ms}ms) ${r.detail}`);
    }
  }

  const rec = pickRecommendation(results, baseURLs);
  if (!rec) {
    console.error('\nAll structured-output methods failed on all base URLs.');
    process.exit(1);
  }
  console.log(`\nRecommended: baseURL=${rec.baseURL} LLM_STRUCTURED_MODE=${rec.mode}`);

  if (process.argv.includes('--write')) {
    updateEnv(rec);
    writeFileSync(DOC_PATH, renderDoc(results, rec));
    console.log('Updated .env (LLM_BASE_URL, LLM_STRUCTURED_MODE) and docs/llm-probe.md');
  }
}

await main();
